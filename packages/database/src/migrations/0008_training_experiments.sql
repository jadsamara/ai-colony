CREATE TABLE "training_experiments" (
	"id" uuid PRIMARY KEY NOT NULL,
	"idempotency_key" text NOT NULL,
	"method_id" text NOT NULL,
	"model_id" text NOT NULL,
	"model_revision" text NOT NULL,
	"adapter_sha256" text,
	"problem" text NOT NULL,
	"dataset_size" integer NOT NULL,
	"learning_rate" double precision NOT NULL,
	"steps" integer NOT NULL,
	"exposures" double precision NOT NULL,
	"target" text NOT NULL,
	"seed" integer NOT NULL,
	"dev_accuracy" double precision,
	"baseline_accuracy" double precision,
	"sealed_accuracy" double precision,
	"retention_ok" boolean,
	"failure_class" text,
	"recommendation" text NOT NULL,
	"evidence_path" text NOT NULL,
	"stopped" boolean DEFAULT false NOT NULL,
	"created_by" text NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "training_experiments_idempotency_key_unique" UNIQUE("idempotency_key"),
	CONSTRAINT "training_experiments_target_check" CHECK (target in ('answer', 'structured'))
);
