CREATE TABLE "routing_decisions" (
  "id" uuid PRIMARY KEY,
  "task_id" uuid,
  "objective_id" uuid NOT NULL,
  "purpose" text NOT NULL,
  "department_id" uuid NOT NULL,
  "assignment_id" uuid,
  "assignment_version" integer,
  "registry_model_id" uuid NOT NULL,
  "serving_model" text NOT NULL,
  "model_digest" text,
  "adapter_id" text,
  "adapter_version" text,
  "policy_version" text NOT NULL,
  "authorization" text NOT NULL,
  "reason_code" text NOT NULL,
  "runtime_evidence" jsonb NOT NULL,
  "budget_outcome" text NOT NULL,
  "resource_outcome" text NOT NULL,
  "fallback_status" text NOT NULL,
  "execution_verification" text NOT NULL,
  "capability_note" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "routing_decisions_task_fk" FOREIGN KEY ("task_id") REFERENCES "objective_tasks"("id") ON DELETE restrict,
  CONSTRAINT "routing_decisions_objective_fk" FOREIGN KEY ("objective_id") REFERENCES "objective_runs"("id") ON DELETE restrict,
  CONSTRAINT "routing_decisions_department_fk" FOREIGN KEY ("department_id") REFERENCES "departments"("id") ON DELETE restrict,
  CONSTRAINT "routing_decisions_assignment_fk" FOREIGN KEY ("assignment_id") REFERENCES "department_model_assignments"("id") ON DELETE restrict,
  CONSTRAINT "routing_decisions_model_fk" FOREIGN KEY ("registry_model_id") REFERENCES "models"("id") ON DELETE restrict,
  CONSTRAINT "routing_decisions_authorization_check" CHECK ("authorization" in ('authorized', 'denied')),
  CONSTRAINT "routing_decisions_fallback_check" CHECK ("fallback_status" = 'disabled'),
  CONSTRAINT "routing_decisions_verification_check" CHECK ("execution_verification" in ('unverified', 'matched', 'mismatch'))
);
CREATE UNIQUE INDEX "routing_decisions_task_unique" ON "routing_decisions" ("task_id") WHERE "task_id" is not null;
CREATE UNIQUE INDEX "routing_decisions_objective_purpose_unique" ON "routing_decisions" ("objective_id", "purpose") WHERE "task_id" is null;
